/**
 * Generate es/de/fr blog + forum from English, and scrub leftover NBA branding in JSON copy.
 */
import fs from 'node:fs';
import path from 'node:path';
import translate from 'google-translate-api-x';
import { enBlogArticles } from '../src/data/blog/posts/en-articles.ts';
import { enForumPosts } from '../src/data/forum/en-posts.ts';

const root = process.cwd();
const LOCALES = [
  { code: 'es', name: 'Spanish' },
  { code: 'de', name: 'German' },
  { code: 'fr', name: 'French' },
];

const cache = new Map();
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function tr(text, to) {
  if (text == null) return text;
  const key = `${to}::${text}`;
  if (cache.has(key)) return cache.get(key);
  if (!String(text).trim() || /^[0-9$€./-]+$/.test(text)) {
    cache.set(key, text);
    return text;
  }
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      const result = await translate(text, { from: 'en', to, forceBatch: false });
      const out = Array.isArray(result) ? result.map((row) => row.text).join(' ') : result.text;
      cache.set(key, out);
      await delay(120);
      return out;
    } catch (error) {
      await delay(600 * (attempt + 1));
      if (attempt === 4) throw error;
    }
  }
  return text;
}

async function translateBlock(block, to) {
  if (block.type === 'ul') {
    return { type: 'ul', items: await Promise.all(block.items.map((item) => tr(item, to))) };
  }
  if (block.type === 'cta') {
    return {
      ...block,
      title: await tr(block.title, to),
      text: await tr(block.text, to),
    };
  }
  if (block.text) {
    return { ...block, text: await tr(block.text, to) };
  }
  return block;
}

async function translateBlog(article, to) {
  return {
    slug: article.slug,
    title: await tr(article.title, to),
    h1: await tr(article.h1, to),
    tag: await tr(article.tag, to),
    desc: await tr(article.desc, to),
    metaTitle: await tr(article.metaTitle, to),
    metaDescription: await tr(article.metaDescription, to),
    date: article.date,
    readTime: article.readTime,
    featured: article.featured,
    author: await tr(article.author, to),
    image: article.image,
    imageAlt: await tr(article.imageAlt, to),
    imageWidth: article.imageWidth,
    imageHeight: article.imageHeight,
    body: await Promise.all(article.body.map((block) => translateBlock(block, to))),
  };
}

async function translateForum(post, to) {
  return {
    ...post,
    category: await tr(post.category, to),
    title: await tr(post.title, to),
    excerpt: await tr(post.excerpt, to),
    author: await tr(post.author, to),
    body: await Promise.all(post.body.map((line) => tr(line, to))),
    comments: await Promise.all(
      post.comments.map(async (comment) => ({
        ...comment,
        author: await tr(comment.author, to),
        body: await tr(comment.body, to),
      })),
    ),
    sourceTitle: await tr(post.sourceTitle, to),
    sourcePath: post.sourcePath,
  };
}

function writeTs(file, exportName, value, typeImport) {
  const json = JSON.stringify(value, null, 2);
  const contents = `// Generated by scripts/rebrand-translate-locales.mjs
import type { ${typeImport} } from '${typeImport === 'BlogPostFull' ? '../types' : './types'}';

export const ${exportName}: ${typeImport}[] = ${json};
`;
  fs.writeFileSync(file, contents);
}

const replacements = [
  [/NBA2K27 CHEATS/g, 'Deadlock Hacks'],
  [/NBA2K27 Cheats/g, 'Deadlock Hacks'],
  [/NBA2K27/g, 'Deadlock'],
  [/NBA 2K27/g, 'Deadlock'],
  [/NBA-2K27/g, 'Deadlock'],
  [/nba 2k27/gi, 'Deadlock'],
  [/Auto Green/g, 'Aimbot'],
  [/Verde automático/g, 'Aimbot'],
  [/nbacheats\.com/g, 'deadlockhacks.net'],
  [/https:\/\/nba\.2k\.com\/2k27\//g, 'https://playdeadlock.com/'],
  [/https:\/\/store\.steampowered\.com\/app\/4356430\/NBA_2K27\//g, 'https://store.steampowered.com/app/1422450/Deadlock/'],
  [/https:\/\/www\.take2games\.com\//g, 'https://www.valvesoftware.com/'],
  [/Take-Two Interactive/g, 'Valve'],
  [/Take-Two/g, 'Valve'],
  [/\/go\/nba-2k27\//g, '/go/deadlock/'],
  [/\/blog\/nba-2k27-product-research-checklist\//g, '/blog/deadlock-product-research-checklist/'],
  [/Visual Concepts/g, 'Valve'],
  [/MyCAREER \/ City \/ modes/g, 'Lanes and objectives'],
  [/MyCAREER/g, 'lanes'],
];

function scrub(value) {
  if (typeof value === 'string') {
    let out = value;
    for (const [pattern, next] of replacements) out = out.replace(pattern, next);
    return out;
  }
  if (Array.isArray(value)) return value.map(scrub);
  if (value && typeof value === 'object') {
    const out = {};
    for (const [key, child] of Object.entries(value)) out[key] = scrub(child);
    return out;
  }
  return value;
}

function scrubJsonFile(rel) {
  const file = path.join(root, rel);
  if (!fs.existsSync(file)) return;
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  fs.writeFileSync(file, `${JSON.stringify(scrub(parsed), null, 2)}\n`);
  console.log(`scrubbed ${rel}`);
}

const jsonTargets = [
  'src/i18n/dictionaries/es.json',
  'src/i18n/dictionaries/de.json',
  'src/i18n/dictionaries/fr.json',
  'src/i18n/pageSeo/es.json',
  'src/i18n/pageSeo/de.json',
  'src/i18n/pageSeo/fr.json',
  'src/data/products/locales/es.json',
  'src/data/products/locales/de.json',
  'src/data/products/locales/fr.json',
  'src/data/catalogCopy/locales/es.json',
  'src/data/catalogCopy/locales/de.json',
  'src/data/catalogCopy/locales/fr.json',
  'src/data/faq/locales/es.json',
  'src/data/faq/locales/de.json',
  'src/data/faq/locales/fr.json',
];

for (const file of jsonTargets) scrubJsonFile(file);

const meta = { es: {}, de: {}, fr: {} };

for (const locale of LOCALES) {
  console.log(`translating blog → ${locale.code}`);
  const blog = [];
  for (const article of enBlogArticles) {
    blog.push(await translateBlog(article, locale.code));
    process.stdout.write('.');
  }
  console.log('');
  writeTs(
    path.join(root, `src/data/blog/posts/${locale.code}-articles.ts`),
    `${locale.code}BlogArticles`,
    blog,
    'BlogPostFull',
  );
  for (const article of blog) meta[locale.code][article.slug] = article.metaDescription;

  console.log(`translating forum → ${locale.code}`);
  const forum = [];
  for (const post of enForumPosts) {
    forum.push(await translateForum(post, locale.code));
    process.stdout.write('.');
  }
  console.log('');
  writeTs(
    path.join(root, `src/data/forum/${locale.code}-posts.ts`),
    `${locale.code}ForumPosts`,
    forum,
    'ForumPost',
  );
}

function writeMeta() {
  const file = path.join(root, 'src/data/blog/metaDescriptions.ts');
  const contents = `import type { SiteLocale } from '../../i18n/locales';

const es: Record<string, string> = ${JSON.stringify(meta.es, null, 2)};
const de: Record<string, string> = ${JSON.stringify(meta.de, null, 2)};
const fr: Record<string, string> = ${JSON.stringify(meta.fr, null, 2)};

const byLocale: Record<Exclude<SiteLocale, 'en'>, Record<string, string>> = { es, de, fr };

export function localeMetaDescriptionOverride(slug: string, locale: SiteLocale): string | undefined {
  if (locale === 'en') return undefined;
  return byLocale[locale][slug];
}
`;
  fs.writeFileSync(file, contents);
  console.log('wrote metaDescriptions.ts');
}

writeMeta();
console.log('locale rebrand complete');
